//! Future system-service metadata. Paths are identities, not executables
//! that ZillaOS can currently spawn. No automatic grants of requested rights.
use super::{MANIFEST_SCHEMA_V1, Quotas, RestartPolicy, ServiceManifest, StartMode};

const fn manifest(
    id: &'static str,
    executable: &'static str,
    start: StartMode,
    required: &'static [&'static str],
    after: &'static [&'static str],
    caps: &'static [&'static str],
    memory: u64,
    threads: u8,
    retries: u8,
) -> ServiceManifest {
    ServiceManifest {
        schema_version: MANIFEST_SCHEMA_V1,
        version: 1,
        id,
        executable,
        start,
        required,
        after,
        requested_capabilities: caps,
        quotas: Quotas {
            memory_bytes: memory,
            threads,
        },
        restart: RestartPolicy::OnFailure {
            max_retries: retries,
            base_ms: 250,
            cap_ms: 30_000,
        },
    }
}

